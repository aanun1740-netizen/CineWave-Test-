-- KinoLab staging: independent catalog of outbound movie links.
-- This does not host/stream content, and does not alter the existing movies rights gate.
BEGIN;
CREATE TABLE IF NOT EXISTS public.kinolab_external_catalog (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title_en text NOT NULL CHECK (length(btrim(title_en)) BETWEEN 1 AND 250),
 title_ru text,
 title_hy text,
 overview_en text,
 overview_ru text,
 overview_hy text,
 release_date date,
 genre_names text[] NOT NULL DEFAULT '{}',
 poster_path text,
 external_watch_url text NOT NULL CHECK (
   external_watch_url ~ '^https://api[.]nextembed[.]ws/embed/(movie|tv)/[0-9]+(/[0-9]+/[0-9]+)?/?$'
 ),
 is_published boolean NOT NULL DEFAULT false,
 terms_confirmed boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT external_catalog_publication CHECK (NOT is_published OR terms_confirmed),
 CONSTRAINT external_catalog_unique_link UNIQUE (external_watch_url)
);
ALTER TABLE public.kinolab_external_catalog ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.kinolab_external_catalog FROM PUBLIC;
GRANT SELECT ON public.kinolab_external_catalog TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.kinolab_external_catalog TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.kinolab_external_catalog_id_seq TO authenticated;
DROP POLICY IF EXISTS kinolab_external_catalog_read ON public.kinolab_external_catalog;
CREATE POLICY kinolab_external_catalog_read ON public.kinolab_external_catalog
 FOR SELECT USING (is_published OR (auth.uid() IS NOT NULL AND public.cinewave_is_admin()));
DROP POLICY IF EXISTS kinolab_external_catalog_insert ON public.kinolab_external_catalog;
CREATE POLICY kinolab_external_catalog_insert ON public.kinolab_external_catalog
 FOR INSERT TO authenticated WITH CHECK (public.cinewave_is_admin());
DROP POLICY IF EXISTS kinolab_external_catalog_update ON public.kinolab_external_catalog;
CREATE POLICY kinolab_external_catalog_update ON public.kinolab_external_catalog
 FOR UPDATE TO authenticated USING (public.cinewave_is_admin()) WITH CHECK (public.cinewave_is_admin());
DROP POLICY IF EXISTS kinolab_external_catalog_delete ON public.kinolab_external_catalog;
CREATE POLICY kinolab_external_catalog_delete ON public.kinolab_external_catalog
 FOR DELETE TO authenticated USING (public.cinewave_is_admin());
COMMIT;
